        <p>NIS2 je europska direktiva čiji je cilj podići razinu kibernetičke sigurnosti kod tvrtki i institucija koje pružaju ključne ili važne usluge — od energetike i zdravstva do digitalne infrastrukture i proizvodnje.</p>

        <h2>Tko mora primjenjivati NIS2</h2>
        <p>Obveze se ne odnose samo na velike korporacije. Direktiva obuhvaća i srednje tvrtke u definiranim sektorima, a mnoge manje tvrtke pogađa neizravno — kao dobavljači tvrtkama koje regulativa izravno obuhvaća.</p>

        <h2>Ključne obveze koje donosi</h2>
        <ul>
          <li>Uspostava sustava za upravljanje sigurnosnim rizicima</li>
          <li>Prijavljivanje ozbiljnih sigurnosnih incidenata nadležnim tijelima u propisanom roku</li>
          <li>Redovita procjena rizika dobavljačkog lanca</li>
          <li>Osobna odgovornost uprave za nadzor nad provedbom mjera</li>
        </ul>

        <h2>Kako se pripremiti</h2>
        <p>Prvi korak je procjena obuhvaća li regulativa vašu tvrtku izravno ili neizravno. Zatim slijedi pregled postojećih sigurnosnih mjera i usporedba s onim što NIS2 traži, te izrada plana za popunjavanje praznina prije rokova koje propisuje nacionalno zakonodavstvo.</p>

